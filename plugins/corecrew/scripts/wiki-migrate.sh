#!/usr/bin/env bash
# wiki-migrate.sh — convert an existing (0.6-format) wiki to the current one
# (rules in reference/wiki.md).
#
# Usage: wiki-migrate.sh <project_dir> [--dry-run]
#   <project_dir>  the Core project folder (has docs/); the INDEX title uses its folder name.
#   --dry-run      print what would change; change nothing.
# Env:   WIKI_MIGRATE_DATES  a folder in the git repo whose docs/ the pages came from (adopt passes the
#                            code repo); default <project_dir>.
#
# Pages are what wiki-pages.sh lists. Per page: title dropped; fields in the order type status
# description files related updated, other fields kept after them in their order and warned about (a brief's
# stage: <v> instead moves to a last body section "## Progress" with the line "Stage: <v>", unless
# the value is empty or multi-line, the body already has that section, or the body ends inside an open
# code fence: then the field stays and is warned); missing ones added
# (an empty value without continuation lines counts as missing; a multi-line one is kept line for line):
# type from the path (brief.md, architecture.md, glossary.md, decisions/, features/, specs/, plans/; else
# none), status draft, description "TODO: describe this page.", files [], related [], updated = date of
# the last commit of the file (WIKI_MIGRATE_DATES repo, original path) or today. related paths and body
# Markdown links to wiki pages become [[name]] ([[name|text]] when the text is not the name, a "|" in
# the text becomes "/"; "page.md#h" keeps #h only when h is a heading of that page). An old reference
# "docs/<page>.md § <text>" (also with the path in backticks, or as the whole of a `code span`) becomes
# [[page#H]], H = the longest heading of that page that starts <text> at a word boundary; the rest of
# the line stays (a code span allows one trailing . , ; : or ) after H). No such heading: the text stays.
# Nothing else inside code fences or `code spans` changes. docs/superpowers/specs/* and plans/* move to
# docs/specs/ and docs/plans/. The Obsidian files (wiki.base, .obsidian/app.json, .obsidian/.gitignore)
# come from the new-project templates; INDEX.md is regenerated by wiki-index.sh.
# All work is done in a copy of docs/ inside <project_dir>, swapped in with two mv at the end; TERM, INT
# and HUP during the swap undo it, and the temp folder is never removed while it holds the only docs/.
#
# Output (stdout, after success): "moved <old> -> <new>" or "updated docs/<page>" per changed page in
# path order; "created|skipped docs/<vault file>"; the wiki-index.sh line; then, in page order,
# "warning: <name>: set type" | "description over 80 chars" | "status <v>" | "anchor #<a> dropped" |
# "reference to <page> § <rest of the line> not converted" | "description is not one line" (it starts
# with > or |) | "extra front matter field <k>" | "front matter not closed" (such a page is left as it is); then
# "warning: CLAUDE.md:<N>: still says docs/superpowers|map line; update it by hand" per 0.6 line of
# <project_dir>/CLAUDE.md (never edited), and "warning: leftover <folder> from an interrupted run; check
# and remove it by hand" per <project_dir>/.wiki-migrate.* left by a killed run (kept).
# Exit: 0 done (or nothing to do); 1 a step failed, one line on stderr, nothing changed (also: a move
# target exists; docs/, or docs/ superpowers, superpowers/specs, superpowers/plans, specs, plans or
# .obsidian is a symlink); 2 usage error.
set -u
HERE="$(cd "$(dirname "$0")" && pwd)"
TPL="$HERE/../skills/new-project/templates/docs"
usage() { echo "usage: wiki-migrate.sh <project_dir> [--dry-run]" >&2; exit 2; }
dry=0; proj=""; seen=0
for a in "$@"; do
  case "$a" in
    --dry-run) dry=1 ;;
    -*) usage ;;
    *) [ "$seen" -eq 0 ] || usage; proj="$a"; seen=1 ;;
  esac
done
proj="${proj%/}"
[ -n "$proj" ] && [ -d "$proj/docs" ] || usage
docs="$proj/docs"; name="$(basename "$proj")"
DATES="${WIKI_MIGRATE_DATES:-$proj}"
TODAY="$(date +%Y-%m-%d)"
export GIT_LITERAL_PATHSPECS=1

S=""
# The temp folder goes on every exit, but never while it holds the only docs/ (S/old with docs/ missing):
# that one is put back first, or kept and named.
cleanup() {
  [ -n "$S" ] || return 0
  if [ -d "$S/old" ] && [ ! -e "$docs" ] && [ ! -L "$docs" ]; then
    mv "$S/old" "$docs" 2>/dev/null || { echo "wiki-migrate: docs/ was not put back; it is in $S/old" >&2; return 0; }
  fi
  chmod -R u+w "$S" 2>/dev/null; rm -rf "$S"
}
trap cleanup EXIT
die() { printf 'wiki-migrate: %s\n' "$1" >&2; exit 1; }

[ ! -L "$docs" ] || die "$docs is a symlink; nothing was changed"
# A link inside docs/ would take the moves and writes out of the copy (and a dry run's cleanup with them).
for k in superpowers superpowers/specs superpowers/plans specs plans .obsidian; do
  [ ! -L "$docs/$k" ] || die "docs/$k is a symlink; nothing was changed"
done
# Refuse a move whose target exists before anything is copied.
for k in specs plans; do
  [ -d "$docs/superpowers/$k" ] || continue
  for f in "$docs/superpowers/$k"/* "$docs/superpowers/$k"/.[!.]*; do
    { [ -e "$f" ] || [ -L "$f" ]; } || continue
    t="$docs/$k/$(basename "$f")"
    { [ ! -e "$t" ] && [ ! -L "$t" ]; } || die "target exists: docs/$k/$(basename "$f"); nothing was changed"
  done
done

# Taken before the temp folder exists, so this run's own folder is not among them.
LEFT=""; for f in "$proj"/.wiki-migrate.*; do { [ -e "$f" ] || [ -L "$f" ]; } && LEFT="$LEFT$f
"; done
if [ "$dry" -eq 1 ]; then S="$(mktemp -d "${TMPDIR:-/tmp}/wiki-migrate.XXXXXX")" || die "cannot create a temp folder"
else S="$(mktemp -d "$proj/.wiki-migrate.XXXXXX" 2>/dev/null)" || { S=""; die "cannot create a temp folder in $proj; nothing was changed"; }; fi
SP="$S/new/$name"; SD="$SP/docs"; W="$S/.work"
mkdir -p "$SP" && mkdir "$W" && cp -Rp "$docs" "$SD" 2>/dev/null || die "could not copy $docs (unreadable file?); nothing was changed"
: > "$W/lines"; : > "$W/warn"; : > "$W/moved"

# Moves inside the copy; "<new>|<old>" (docs-relative) in $W/moved.
for k in specs plans; do
  [ -d "$SD/superpowers/$k" ] || continue
  for f in "$SD/superpowers/$k"/* "$SD/superpowers/$k"/.[!.]*; do
    { [ -e "$f" ] || [ -L "$f" ]; } || continue
    b="$(basename "$f")"
    mkdir -p "$SD/$k" && mv "$f" "$SD/$k/$b" || die "could not move docs/superpowers/$k/$b; nothing was changed"
    printf '%s|%s\n' "$k/$b" "superpowers/$k/$b" >> "$W/moved"
  done
  rmdir "$SD/superpowers/$k" 2>/dev/null
done
rmdir "$SD/superpowers" 2>/dev/null

"$HERE/wiki-pages.sh" "$SD" > "$W/pages" || die "could not list the pages"
# Page names, and "name<TAB>heading" for every # to ###### heading outside front matter and fences.
LC_ALL=C awk -v D="$SD" '
  function trim(s) { gsub(/^[ \t]+|[ \t]+$/, "", s); return s }
  { n = $0; sub(/.*\//, "", n); sub(/\.md$/, "", n); print n > NAMES; f = D "/" $0; fm = 0; fence = 0; ln = 0
    while ((getline l < f) > 0) {
      sub(/\r$/, "", l)
      if (++ln == 1 && l ~ /^---[ \t]*$/) { fm = 1; continue }
      if (fm) { if (l ~ /^---[ \t]*$/) fm = 0; continue }
      if (l ~ /^[ \t]*(```|~~~)/) { fence = !fence; continue }
      if (!fence && match(l, /^#+[ \t]/) && RLENGTH <= 7) {
        t = trim(substr(l, RLENGTH + 1)); sub(/[ \t]+#+$/, "", t); print n "\t" trim(t) }
    }
    close(f) }
' NAMES="$W/names" "$W/pages" > "$W/heads" || die "could not read the pages; nothing was changed"
: >> "$W/names"

while IFS= read -r pg; do
  [ -n "$pg" ] || continue
  f="$SD/$pg"; n="$(basename "$pg" .md)"
  orig="$(awk -F'|' -v p="$pg" '$1 == p { print $2; exit }' "$W/moved")"
  case "$pg" in
    brief.md) ty=brief ;; architecture.md) ty=architecture ;; glossary.md) ty=glossary ;;
    decisions/*) ty=decision ;; features/*) ty=feature ;; specs/*) ty=spec ;; plans/*) ty=plan ;; *) ty="" ;;
  esac
  # The commit date, needed when the front matter has no non-empty updated: (body lines do not count).
  if LC_ALL=C awk '{ sub(/\r$/, "") } NR == 1 { if ($0 !~ /^---[ \t]*$/) exit 1; next }
      /^---[ \t]*$/ { exit 1 } /^updated:[ \t]*[^ \t]/ { exit 0 } END { if (NR < 2) exit 1 }' "$f"; then d=""
  else d="$(git -C "$DATES" log -1 --format=%cd --date=short -- "docs/${orig:-$pg}" 2>/dev/null)"; fi
  LC_ALL=C awk -v SQ="'" -v NAME="$n" -v TYPE="$ty" -v DATE="${d:-$TODAY}" -v NAMES="$W/names" \
    -v HEADS="$W/heads" -v WARN="$W/warn" -f "$HERE/wiki-migrate.awk" "$f" > "$W/page" || die "could not convert docs/$pg; nothing was changed"
  # awk ends every line with a newline: a page that had no final one keeps having none
  if [ -s "$f" ] && [ -n "$(tail -c1 "$f")" ] && [ -z "$(tail -c1 "$W/page")" ]; then
    sz="$(wc -c < "$W/page" | tr -d " ")"; head -c "$((sz - 1))" "$W/page" > "$W/page1" && mv "$W/page1" "$W/page" \
      || die "could not convert docs/$pg; nothing was changed"
  fi
  if [ -n "$orig" ]; then line="moved docs/$orig -> docs/$pg"
  elif cmp -s "$W/page" "$f"; then continue
  else line="updated docs/$pg"; fi
  cmp -s "$W/page" "$f" || cat "$W/page" > "$f" || die "could not write docs/$pg; nothing was changed"
  printf '%s\n' "$line" >> "$W/lines"
done < "$W/pages"
# Moved files that are not pages (pages already have their line).
while IFS='|' read -r new old; do
  [ -n "$new" ] || continue
  grep -qxF -- "$new" "$W/pages" || printf 'moved docs/%s -> docs/%s\n' "$old" "$new" >> "$W/lines"
done < "$W/moved"
cp "$W/lines" "$W/sorted" || die "could not write a temp file"   # already in page order

# The Obsidian files; an existing one is kept.
for pair in "wiki.base|wiki.base" "obsidian-app.json|.obsidian/app.json" "obsidian-gitignore|.obsidian/.gitignore"; do
  src="${pair%%|*}"; dst="${pair#*|}"
  if [ -e "$SD/$dst" ] || [ -L "$SD/$dst" ]; then echo "skipped docs/$dst"
  else mkdir -p "$(dirname "$SD/$dst")" && cp "$TPL/$src" "$SD/$dst" || die "could not create docs/$dst; nothing was changed"
    echo "created docs/$dst"; fi
done >> "$W/sorted"
# (the pages' type warnings are above; wiki-index's own notes about them would repeat them)
WIKI_INDEX_UNTYPED=1 bash "$HERE/wiki-index.sh" "$SP" >> "$W/sorted" 2>/dev/null || die "wiki-index.sh failed; nothing was changed"
# 0.6 instructions in CLAUDE.md, and leftovers of a killed run: named, never touched.
if [ -f "$proj/CLAUDE.md" ]; then
  awk '/docs\/superpowers/ { print "warning: CLAUDE.md:" NR ": still says docs/superpowers; update it by hand"; next }
       /map line/ { print "warning: CLAUDE.md:" NR ": still says map line; update it by hand" }' "$proj/CLAUDE.md" >> "$W/warn" \
    || die "could not read $proj/CLAUDE.md; nothing was changed"
fi
printf '%s' "$LEFT" | while IFS= read -r f; do
  [ -n "$f" ] && printf 'warning: leftover %s from an interrupted run; check and remove it by hand\n' "$f"
done >> "$W/warn"

# The swap: the old docs/ goes into the temp folder, the copy takes its place. TERM, INT and HUP wait
# until both moves are done; a signal that came in between undoes the swap (docs/ as it was).
if [ "$dry" -eq 0 ] && grep -qE '^(moved|updated|created) ' "$W/sorted"; then
  GOT=0; trap 'GOT=1' TERM INT HUP
  mv "$docs" "$S/old" 2>/dev/null || die "could not replace $docs; nothing was changed"
  if ! mv "$SD" "$docs" 2>/dev/null; then
    mv "$S/old" "$docs" || { k="$S/old"; S=""; die "could not put $docs back; it is in $k"; }
    die "could not replace $docs; nothing was changed"
  fi
  if [ "$GOT" -eq 1 ]; then
    mv "$docs" "$S/.undone" && mv "$S/old" "$docs" || { k="$S"; S=""; die "interrupted; the old docs/ is in $k/old"; }
    die "interrupted; nothing was changed"
  fi
  trap - TERM INT HUP
fi
cat "$W/sorted" "$W/warn"
exit 0
